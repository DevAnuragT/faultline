"""`faultline init`: probe what is reachable and write a starter profile the user then edits."""
from __future__ import annotations

import subprocess
from pathlib import Path

import requests
import yaml


def _services(jaeger: str) -> list[str]:
    try:
        r = requests.get(f"{jaeger.rstrip('/')}/api/services", timeout=10); r.raise_for_status()
        return [s for s in r.json().get("data") or [] if s != "jaeger-all-in-one"]
    except Exception:
        return []


def _roots(jaeger: str, services: list[str]) -> list[str]:
    roots = set()
    for svc in services:
        try:
            r = requests.get(f"{jaeger.rstrip('/')}/api/traces", params={"service": svc, "limit": 5, "lookback": "24h"}, timeout=15)
            for t in r.json().get("data") or []:
                procs = {k: v["serviceName"] for k, v in t["processes"].items()}
                for s in t["spans"]:
                    if not s.get("references"):
                        roots.add(procs[s["processID"]])
        except Exception:
            pass
    return sorted(roots)


def _compose_services(compose: str) -> list[str]:
    p = Path(compose)
    if not p.exists():
        return []
    try:
        r = subprocess.run(["docker", "compose", "-f", str(p), "config", "--services"], capture_output=True, text=True, timeout=30)
        return [x for x in r.stdout.split() if x] if r.returncode == 0 else list((yaml.safe_load(p.read_text()) or {}).get("services", {}))
    except Exception:
        return list((yaml.safe_load(p.read_text()) or {}).get("services", {}))


def write_starter(jaeger: str, compose: str, out: str) -> str:
    services = _services(jaeger)
    roots = _roots(jaeger, services)
    compose_services = _compose_services(compose)
    infra = {"jaeger", "falkordb", "otel-collector", "collector", "tempo", "prometheus", "grafana"}
    svc_map = {}
    for s in services:
        match = s if s in compose_services else next((c for c in compose_services if c in s or s in c), None)
        if match and match not in infra:
            svc_map[s] = {"compose": match}
        else:
            svc_map[s] = {"in_process_of": "<the service this runs inside, or delete this line>"} if any(k in s.lower() for k in ("mysql", "redis", "postgres", "db", "cache", "kafka")) else {}
    doc = {
        "name": Path(out).stem if Path(out).stem != "faultline" else Path.cwd().name,
        "traces": ({"source": "jaeger", "jaeger_url": jaeger} if services else {"source": "otlp"}) | {"root_services": list(roots), "edge_services": list(roots)},
        "load": {"urls": ["http://localhost:8080/<an endpoint that exercises the system>"], "requests": 40, "parallel": 4, "timeout_s": 35},
        "environment": {"backend": "compose" if compose_services else "none", "compose_file": compose},
        "services": svc_map,
        "actuators": [{"id": "example-pool", "kind": "serialized_fanout", "service": roots[0] if roots else "<service>", "target": roots[0] if roots else "<service>",
                       "change": {"env": {"WORKER_POOL": "100"}}, "what": "raise the worker pool; replace with a change YOUR service supports, or delete"}],
        "code": {"source_root": "", "raw_base": "", "repo_url": "", "map": []},
        "slo": {"endpoint": "", "p95_ms": None, "fail_rate": None},
    }
    text = ("# Faultline profile for your system. Generated by `faultline init`; edit before use.\n"
            "# services: map each trace service name to its compose service (or kubernetes deployment); stores that run inside a service use in_process_of.\n"
            "# actuators: the ONLY changes Faultline may apply; each maps a remedy class (contention | serialized_fanout | per_call_cost) to a change.\n"
            "# load: delete the block to run observe-only (ingest live traffic with `faultline ingest --lookback 15m`).\n"
            + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True))
    Path(out).write_text(text)
    return (f"wrote {out}: " + ("no Jaeger reachable: traces.source set to otlp (export OTLP to http://<faultline>:8600/v1/traces). " if not services else "") + f"{len(services)} services from Jaeger ({', '.join(services) or 'none reachable'}), roots {roots or 'none found'}, "
            f"{len(compose_services)} compose services. Edit it, then: FAULTLINE_PROFILE={out} faultline baseline")
